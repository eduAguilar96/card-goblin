// Regenerates src/lib/lang/dicier-codes.ts from the vendored Dicier codes list.
// Parse rules per docs/DESIGN.md §4.1: skip ':'-suffixed category headers, blank
// lines, and literal 'etc.' lines; deduplicate across sections; keep codes that
// contain spaces. The list is known non-exhaustive (see DESIGN.md §9) — unknown
// codes are a warning (W004), not an error.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "docs/vendor/dicier-v1.5.4/Dicier codes v1_5_4.txt");
const target = join(root, "src/lib/lang/dicier-codes.ts");

const codes = new Set();
for (const raw of readFileSync(source, "utf8").split(/\r?\n/)) {
  const line = raw.trim();
  if (!line) continue;
  if (line.endsWith(":")) continue; // category header (any language)
  if (/^etc\.?$/i.test(line)) continue; // explicit non-exhaustiveness marker
  codes.add(line);
}

const sorted = [...codes].sort();
const body = sorted.map((c) => `  ${JSON.stringify(c)},`).join("\n");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-dicier-codes.mjs — do not edit by hand.
// ${sorted.length} unique codes from Dicier v1.5.4 (list is non-exhaustive; see docs/DESIGN.md §9).
export const DICIER_CODES: ReadonlySet<string> = new Set([
${body}
]);
`,
);
console.log(`Wrote ${sorted.length} codes to ${target}`);
